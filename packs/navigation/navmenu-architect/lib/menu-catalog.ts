export interface MenuFilterCriteria {
  kind: 'all' | MenuKind;
  style: 'all' | MenuStyle;
  query: string;
}

export function filterMenus(
  menus: MenuCatalogEntry[],
  criteria: MenuFilterCriteria,
): MenuCatalogEntry[] {
  const normalizedQuery = criteria.query.trim().toLowerCase();

  return menus.filter((menu) => {
    if (criteria.kind !== 'all' && menu.kind !== criteria.kind) {
      return false;
    }
    if (criteria.style !== 'all' && menu.style !== criteria.style) {
      return false;
    }
    if (!normalizedQuery) {
      return true;
    }
    const haystack = [
      menu.componentName,
      menu.brand,
      menu.triggerLabel,
      menu.kindLabel,
      menu.styleLabel,
      menu.rowStyleLabel,
      menu.groupingLabel,
      menu.topology,
      menu.searchPlacement,
      menu.summary,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(normalizedQuery);
  });
}
